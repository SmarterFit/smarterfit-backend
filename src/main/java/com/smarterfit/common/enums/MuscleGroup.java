package com.smarterfit.common.enums;

public enum MuscleGroup {
    // Upper Body
    CHEST,          // Peito
    BACK,           // Costas
    SHOULDERS,      // Ombros
    BICEPS,         // Bíceps
    TRICEPS,        // Tríceps
    FOREARMS,       // Antebraços

    // Lower Body
    QUADS,          // Quadríceps
    HAMSTRINGS,     // Posterior de coxa
    GLUTES,         // Glúteos
    CALVES,         // Panturrilhas

    // Core
    ABS,            // Abdominais
    OBLIQUES,       // Oblíquos
    LOWER_BACK,     // Lombar

    // Full Body / Functional
    FULL_BODY,      // Corpo inteiro
    PUSH,           // Empurrar (peito, ombro, tríceps)
    PULL,           // Puxar (costas, bíceps)
    LEGS,           // Pernas (quadríceps, posterior)
    ARMS,           // Braços (bíceps + tríceps)
    CORE,           // Core completo (abdômen + lombar)
    UPPER_BODY,    // Parte superior do corpo (peito + costas + ombros + braços)
    LOWER_BODY,    // Parte inferior do corpo (pernas + glúteos)

}